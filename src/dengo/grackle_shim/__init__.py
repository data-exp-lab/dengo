"""dengo-grackle: build a drop-in replacement for Grackle's C library
(`libgrackle` + `grackle.h`, Grackle 3.4.1 API) backed by dengo's
primordial H/He/H2 network, so codes written against Grackle -- Enzo,
unmodified -- can link it instead.

    python -m dengo.grackle_shim --prefix /path/to/dengo-grackle

writes `include/` (Grackle's public headers), `lib/libgrackle.{a,so}`
and `share/dengo-grackle/` (generated sources, build info) under the
prefix. Point a Grackle-using build at that prefix -- e.g. Enzo's
`-DGRACKLE_ROOT=/path/to/dengo-grackle`. See README.md in this package.
"""
import argparse
import os
import shutil
import subprocess

import numpy as np

import dengo.c_build as c_build

SOLVER = "primordial"
GRACKLE_API_VERSION = "3.4.1"
THREE_BODY_VARIANTS = range(6)   # Grackle's three_body_rate 0..5

_HERE = os.path.dirname(os.path.abspath(__file__))
_VENDOR = os.path.join(_HERE, "vendor")


def _dengo_version():
    try:
        out = subprocess.run(["git", "-C", _HERE, "describe", "--always", "--dirty"],
                             capture_output=True, text=True, check=True)
        return "dengo " + out.stdout.strip()
    except Exception:  # noqa: BLE001 -- not a git checkout
        import importlib.metadata
        try:
            return "dengo " + importlib.metadata.version("dengo")
        except Exception:  # noqa: BLE001
            return "dengo (unknown version)"


def _table_arrays(network):
    """All tables, in tables-file order, as a (ntables, nbins) array, plus
    a name for each (for locating specific tables)."""
    rows, names = [], []
    for name, rxn in sorted(network.reactions.items()):
        rows.append(rxn.coeff_fn(network)); names.append("r_" + name)
    for name, action in sorted(network.cooling_actions.items()):
        for tab in sorted(action.tables):
            rows.append(action.tables[tab](network)); names.append("c_%s_%s" % (name, tab))
    for sp in sorted(network.interpolate_gamma_species):
        rows.append(network.interpolate_species_gamma(sp)); names.append("g_gamma" + sp.name)
        rows.append(network.interpolate_species_gamma(sp, deriv=True))
        names.append("g_dgamma%s_dT" % sp.name)
    return np.array(rows, dtype="float64"), names


def _c_double(x):
    if np.isnan(x):
        return "NAN"
    if np.isinf(x):
        return "INFINITY" if x > 0 else "-INFINITY"
    return repr(float(x))


def _c_array(values, per_line=4):
    vals = [_c_double(v) for v in np.ravel(values)]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return "    " + ",\n    ".join(lines)


def _write_tables_source(network, outdir):
    """primordial_grackle_tables.{h,C}: dengo's rate tables for every
    three_body_rate choice, compiled in (no data file at run time)."""
    variants = []
    names = None
    for tb in THREE_BODY_VARIANTS:
        network.threebody = tb
        tables, names = _table_arrays(network)
        variants.append(tables)
    network.threebody = 4
    variants = np.array(variants)            # (nvariant, ntable, nbin)
    nvar, ntab, nbin = variants.shape
    varying = [t for t in range(ntab)
               if not all(np.array_equal(variants[0, t], variants[v, t], equal_nan=True)
                          for v in range(nvar))]
    base = variants[4]                         # dengo's default (Glover 2008)

    def idx(name):
        return names.index(name)

    chemheat = [i for i, nm in enumerate(names)
                if nm.startswith("c_h2formation") and ("_h2mheat" in nm or "_h2mcool" in nm)]
    assert len(chemheat) == 4, chemheat

    T = np.asarray(network.T)
    header = """/* THIS FILE HAS BEEN AUTO-GENERATED BY DENGO (dengo.grackle_shim). DO NOT EDIT. */
#ifndef PRIMORDIAL_GRACKLE_TABLES_H
#define PRIMORDIAL_GRACKLE_TABLES_H
#include "primordial_solver.h"

#define DENGO_GR_VERSION "{version}"
#define DENGO_GR_NVARIANTS {nvar}
#define DENGO_GR_NVARYING {nvarying}
#define DENGO_GR_T_START {tstart}
#define DENGO_GR_T_END {tend}
#define DENGO_GR_TABLE_K01 {k01}
#define DENGO_GR_TABLE_K02 {k02}
#define DENGO_GR_TABLE_CIECO {cieco}
/* Chemical-energy tables (H2 formation heating / dissociation cooling):
   excluded from calculate_cooling_time(), which in Grackle covers
   radiative processes only. */
#define DENGO_GR_NCHEMHEAT {nchem}
static const int dengo_gr_chemheat_tables[DENGO_GR_NCHEMHEAT] = {{{chem}}};

#if PRIMORDIAL_NTABLES != {ntab} || PRIMORDIAL_NBINS != {nbin}
#error "primordial_grackle_tables.h does not match primordial_solver.h"
#endif

extern const double dengo_gr_base_tables[PRIMORDIAL_TABLE_DOUBLES];
extern const int dengo_gr_varying_tables[{nvarying_dim}];
extern const double dengo_gr_variant_tables[DENGO_GR_NVARIANTS][{nvarying_dim}][PRIMORDIAL_NBINS];

#endif
""".format(version=_dengo_version(), nvar=nvar, nvarying=len(varying),
           tstart=repr(float(T[0])), tend=repr(float(T[-1])),
           k01=idx("r_k01"), k02=idx("r_k02"), cieco=idx("c_cie_cooling_cieco"),
           ntab=ntab, nbin=nbin, nvarying_dim=max(len(varying), 1),
           nchem=len(chemheat), chem=", ".join(str(t) for t in chemheat))
    with open(os.path.join(outdir, "primordial_grackle_tables.h"), "w") as f:
        f.write(header)

    src = ["/* THIS FILE HAS BEEN AUTO-GENERATED BY DENGO (dengo.grackle_shim). DO NOT EDIT. */",
           "#include <math.h>",
           '#include "primordial_grackle_tables.h"', "",
           "/* Tables for three_body_rate = 4; see dengo_gr_variant_tables for the rest. */",
           "const double dengo_gr_base_tables[PRIMORDIAL_TABLE_DOUBLES] = {",
           _c_array(base), "};", "",
           "const int dengo_gr_varying_tables[%d] = {%s};" % (
               max(len(varying), 1), ", ".join(str(t) for t in varying) or "0"), "",
           "const double dengo_gr_variant_tables[DENGO_GR_NVARIANTS][%d][PRIMORDIAL_NBINS] = {"
           % max(len(varying), 1)]
    for v in range(nvar):
        src.append("  { /* three_body_rate = %d */" % v)
        rows = [variants[v, t] for t in varying] or [np.zeros(nbin)]
        for r in rows:
            src.append("   {")
            src.append(_c_array(r))
            src.append("   },")
        src.append("  },")
    src.append("};")
    with open(os.path.join(outdir, "primordial_grackle_tables.C"), "w") as f:
        f.write("\n".join(src) + "\n")
    return [names[t] for t in varying]


def _write_grackle_float(include_dir):
    with open(os.path.join(_VENDOR, "include", "grackle_float.h.in")) as f:
        text = f.read()
    with open(os.path.join(include_dir, "grackle_float.h"), "w") as f:
        f.write(text.replace("@GRACKLE_FLOAT_MACRO@", "GRACKLE_FLOAT_8"))


def generate_sources(src_dir):
    """Write every source file the library is built from into `src_dir`;
    returns the list of .C files to compile."""
    from dengo.primordial_network import build_network
    os.makedirs(src_dir, exist_ok=True)
    network = build_network()
    network.write_c_api(SOLVER, output_dir=src_dir)
    varying = _write_tables_source(network, src_dir)
    shutil.copy(os.path.join(_HERE, "grackle_shim.C"), src_dir)
    for fn in ("grackle_chemistry_data_fields.def", "grackle_field_data_fdatamembers.def"):
        shutil.copy(os.path.join(_VENDOR, fn), src_dir)
    sources = [os.path.join(src_dir, fn) for fn in (
        "%s_solver.C" % SOLVER, "%s_c_api.C" % SOLVER, "BE_chem_solve.C",
        "primordial_grackle_tables.C", "grackle_shim.C")]
    return sources, varying


def build(prefix, use_openmp=None, shared=True, static=True):
    """Generate and compile the library into `prefix` (see module
    docstring). Returns a dict describing what was built."""
    prefix = os.path.abspath(prefix)
    include_dir = os.path.join(prefix, "include")
    lib_dir = os.path.join(prefix, "lib")
    share_dir = os.path.join(prefix, "share", "dengo-grackle")
    src_dir = os.path.join(share_dir, "src")
    for d in (include_dir, lib_dir, share_dir):
        os.makedirs(d, exist_ok=True)

    for fn in os.listdir(os.path.join(_VENDOR, "include")):
        if fn.endswith(".h"):
            shutil.copy(os.path.join(_VENDOR, "include", fn), include_dir)
    _write_grackle_float(include_dir)
    shutil.copy(os.path.join(_VENDOR, "LICENSE"), os.path.join(share_dir, "GRACKLE_LICENSE"))

    sources, varying = generate_sources(src_dir)
    # Only the C API's loop over cells is parallel; the solver core it
    # calls once per cell is compiled serially (see build_library).
    serial = [src for src in sources
              if os.path.basename(src) in ("%s_solver.C" % SOLVER, "BE_chem_solve.C",
                                           "primordial_grackle_tables.C")]
    built = c_build.build_library("grackle", sources, lib_dir,
                                  include_dirs=[include_dir, src_dir],
                                  defines=["DENGO_QUIET"], use_openmp=use_openmp,
                                  shared=shared, static=static, serial_sources=serial)
    info = {
        "dengo_version": _dengo_version(),
        "grackle_api_version": GRACKLE_API_VERSION,
        "openmp": built["openmp"],
        "three_body_varying_tables": varying,
    }
    with open(os.path.join(share_dir, "BUILD_INFO"), "w") as f:
        for k, v in info.items():
            f.write("%s: %s\n" % (k, v))
    built.update(info)
    built["prefix"] = prefix
    built["include"] = include_dir
    return built


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="python -m dengo.grackle_shim",
        description="Build a Grackle-API-compatible libgrackle backed by dengo's "
                    "primordial chemistry network.")
    parser.add_argument("--prefix", required=True, help="install prefix (include/, lib/, share/)")
    parser.add_argument("--no-openmp", action="store_true", help="build without OpenMP")
    parser.add_argument("--no-shared", action="store_true", help="skip libgrackle.so")
    parser.add_argument("--no-static", action="store_true", help="skip libgrackle.a")
    args = parser.parse_args(argv)
    built = build(args.prefix, use_openmp=False if args.no_openmp else None,
                  shared=not args.no_shared, static=not args.no_static)
    print("dengo-grackle built in %s" % built["prefix"])
    for key in ("shared", "static"):
        if key in built:
            print("  %s" % built[key])
    print("  headers: %s" % built["include"])
    print("  OpenMP: %s" % ("yes" if built["openmp"] else "no"))
    print("Point your Grackle-using build at the prefix, e.g. for Enzo: "
          "-DGRACKLE_ROOT=%s" % built["prefix"])
