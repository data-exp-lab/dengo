def find_emxx():
    emxx = shutil.which("em++")
    if emxx is None:
        print("em++ not found on PATH -- install/activate the Emscripten SDK "
              "(https://emscripten.org/docs/getting_started/downloads.html)", file=sys.stderr)
        sys.exit(1)
    return emxx


def build_one(name, cfg, out_dir, repo):
    net_dir = os.path.join(out_dir, name)
    os.makedirs(net_dir, exist_ok=True)

    network = cfg["build"]()
    network.write_wasm_solver(name, output_dir=net_dir)

    subprocess.run(
        [
            find_emxx(), "-O3", "-o", "dengo_wasm.js",
            "dengo_wasm.cpp", "%s_solver.C" % name, "BE_chem_solve.C",
            "--embed-file", "%s_tables.bin@%s_tables.bin" % (name, name),
            "-sEXPORTED_FUNCTIONS=%s" % ",".join(EXPORTED_FUNCTIONS),
            "-sEXPORTED_RUNTIME_METHODS=cwrap,ccall,HEAPF64",
            "-sMODULARIZE=1", "-sEXPORT_NAME=DengoModule",
            "-sALLOW_MEMORY_GROWTH=1",
        ],
        cwd=net_dir, check=True,
    )

    species_names = sorted(s.name for s in network.required_species)
    config = {
        "title": cfg["title"],
        "default_ics": cfg["default_ics"],
        "default_T": cfg["default_T"],
        "species_names": species_names,
    }
    with open(os.path.join(net_dir, "index.html"), "w") as f:
        f.write(PAGE_TEMPLATE.format(
            title=cfg["title"], repo=repo, config_json=json.dumps(config),
        ))

    # generated build byproducts not needed by the served page
    for fn in ("%s_solver.h" % name, "%s_solver.C" % name, "BE_chem_solve.C",
               "%s_tables.bin" % name, "dengo_wasm.cpp"):
        os.remove(os.path.join(net_dir, fn))


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "_site")
    repo = os.environ.get("GITHUB_REPOSITORY", "data-exp-lab/dengo")
    os.makedirs(out_dir, exist_ok=True)

    shutil.copy(os.path.join(HERE, "app.js"), out_dir)
    shutil.copy(os.path.join(HERE, "style.css"), out_dir)

    succeeded, failed = [], []
    for name, cfg in FIDUCIAL_NETWORKS.items():
        print("--- building %s ---" % name)
        try:
            build_one(name, cfg, out_dir, repo)
            succeeded.append(name)
        except Exception as exc:
            print("!!! %s failed: %s" % (name, exc), file=sys.stderr)
            failed.append(name)

    items = "\n".join(
        '  <li><a href="%s/">%s</a><div class="desc">%s</div></li>'
        % (name, FIDUCIAL_NETWORKS[name]["title"], FIDUCIAL_NETWORKS[name]["build"].__doc__.strip().split("\n")[0])
        for name in succeeded
    )
    with open(os.path.join(out_dir, "index.html"), "w") as f:
        f.write(LANDING_TEMPLATE.format(items=items))

    print("\nsucceeded: %s" % succeeded)
    if failed:
        print("FAILED: %s" % failed, file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
